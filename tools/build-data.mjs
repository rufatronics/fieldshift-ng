// Build step: pulls the harmonized NASA data from the private Hugging Face dataset and writes public/zones.js.
// HF_TOKEN (read access) is only used here, at build time, and never reaches the browser.
// If anything goes wrong the committed demo zones.js stays in place, so the site still deploys.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const REPO = process.env.HF_REPO || "rufatronics/fieldshift-ng-data";
const TOKEN = process.env.HF_TOKEN, LOCAL = process.env.LOCAL_DIR;
const OUT = new URL("../public/zones.js", import.meta.url);

async function get(file) {
  if (LOCAL) return readFileSync(join(LOCAL, file), "utf8");
  const r = await fetch(`https://huggingface.co/datasets/${REPO}/resolve/main/${file}`, { headers: { Authorization: `Bearer ${TOKEN}` } });
  if (!r.ok) throw new Error(`${file}: HTTP ${r.status}`);
  return r.text();
}
const num = v => (v === "" || v === undefined ? NaN : Number(v));
const mean = a => a.reduce((x, y) => x + y, 0) / a.length;
function parseCsv(t) {
  const [h, ...rows] = t.trim().split(/\r?\n/), cols = h.split(",");
  return rows.map(l => { const v = l.split(","), o = {}; cols.forEach((c, i) => (o[c] = v[i])); return o; });
}
// Monthly climatology across years. total=true: dekad rainfall -> monthly total per year (needs 3 dekads) -> mean over years.
function monthly(rows, col, total) {
  const by = {};
  for (const r of rows) {
    const v = num(r[col]); if (isNaN(v)) continue;
    const y = r.dekad_start.slice(0, 4), m = +r.dekad_start.slice(5, 7);
    ((by[m] ??= {})[y] ??= []).push(v);
  }
  const out = [];
  for (let m = 1; m <= 12; m++) {
    const yrs = Object.values(by[m] || {});
    const vals = total ? yrs.filter(a => a.length >= 3).map(a => a.reduce((x, y) => x + y, 0)) : yrs.flat();
    if (!vals.length) throw new Error(`no data for ${col}, month ${m}`);
    out.push(Math.round(mean(vals) * 100) / 100);
  }
  return out;
}

try {
  if (!TOKEN && !LOCAL) throw new Error("HF_TOKEN not set");
  const [csv, terr, zones, man] = await Promise.all(["dekad_harmonized.csv", "terrain.json", "zones.json", "manifest.json"].map(get));
  const rows = parseCsv(csv), T = JSON.parse(terr), Z = JSON.parse(zones), M = JSON.parse(man);
  if (M.stages?.power !== "ok") throw new Error("manifest: POWER stage is not ok");
  const out = {}; let imerg = false;
  for (const [id, z] of Object.entries(Z)) {
    try {
      const d = rows.filter(r => r.zone === id), t = T[id];
      if (!d.length || !t) throw new Error("no rows or no terrain");
      const okIm = M.stages?.imerg === "ok" && d.filter(r => !isNaN(num(r.imerg_precip_sum_mm))).length / d.length > 0.7;
      imerg ||= okIm;
      out[id] = { name: z.name, rain: monthly(d, okIm ? "imerg_precip_sum_mm" : "power_precip_sum_mm", true),
        tmax: monthly(d, "power_t2m_max_mean_c"), rh: monthly(d, "power_rh2m_mean_pct"), ndvi: monthly(d, "modis_ndvi_mean"),
        lowPos: t.relative_position, slope: t.slope_deg_mean };
    } catch (e) { console.warn(`[fieldshift] skipped zone ${id}: ${e.message}`); }
  }
  if (!Object.keys(out).length) throw new Error("no usable zones");
  const meta = { repo: REPO, years: M.years, generated: new Date().toISOString().slice(0, 10), rainSource: imerg ? "IMERG" : "POWER", zones: Object.keys(out).length };
  writeFileSync(OUT, `// generated by tools/build-data.mjs\nconst DATA_META=${JSON.stringify(meta)};\nfor (const k in ZONES) delete ZONES[k];\nObject.assign(ZONES, ${JSON.stringify(out)});\n`);
  console.log(`[fieldshift] wrote ${meta.zones} zone(s) from ${REPO}; rain: ${meta.rainSource}`);
} catch (e) {
  console.warn(`[fieldshift] using demo zones.js (${e.message})`);
}
